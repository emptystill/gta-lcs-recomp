#!/usr/bin/env python3
"""Declarations and stubs for recompiled functions src/ calls by name that this executable lacks.

src/ still holds the Vice City Stories port's game code (src/game/vcs_*.cpp, debug/selftest.cpp), which names some of
VCS's recompiled functions directly (FUN_00443c30_0x443c30 ...). Liberty City Stories' generated code has other
functions at other addresses, so those names are missing: the sources would not compile or link. This writes, into
the generated folder:

- ps2_compat_functions.h: a declaration for each missing name (the sources include it after
  ps2_recompiled_functions.h, when it exists);
- ps2_compat_functions.cpp: a definition for each that says which one was called and stops the game.

None of them is meant to run: the VCS overrides only apply to VCS's executable (PS2_REGISTER_GAME_OVERRIDE), and each
LCS hook gets its own LCS address. A stub that does run says so in the log ("[compat] ... called").

    python tools/compat_symbols.py generated/ee
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# FUN_00443c30_0x443c30, fn_..., and SDK names the recompiler keeps (ps2__Exit_0x4672c0)
NAME = re.compile(r"\b([A-Za-z_][A-Za-z0-9_]*?_0x[0-9a-fA-F]{5,8})\b")
HEADER = "ps2_compat_functions.h"
SOURCE = "ps2_compat_functions.cpp"


def used_names():
    names = set()
    for d, _, files in os.walk(os.path.join(ROOT, "src")):
        for f in files:
            if f.endswith((".cpp", ".h", ".hpp")):
                with open(os.path.join(d, f), encoding="utf-8", errors="replace") as fh:
                    names.update(NAME.findall(fh.read()))
    return names


def declared_names(generated):
    with open(os.path.join(generated, "ps2_recompiled_functions.h"), encoding="utf-8", errors="replace") as fh:
        return set(NAME.findall(fh.read()))


def write_if_changed(path, text):
    try:
        with open(path, encoding="utf-8") as fh:
            if fh.read() == text:
                return False
    except OSError:
        pass
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return True


def main(generated):
    missing = sorted(used_names() - declared_names(generated))
    sig = "(uint8_t *rdram, R5900Context *ctx, PS2Runtime *runtime)"
    header = ["// Generated by tools/compat_symbols.py: recompiled functions src/ names that this executable lacks.",
              "#pragma once", "#include \"ps2_guest_cc.h\"", "#include <cstdint>", "",
              "struct R5900Context;", "class PS2Runtime;", ""]
    header += ["PS2_GUEST_CC void %s%s;" % (n, sig) for n in missing]
    source = ["// Generated by tools/compat_symbols.py: stubs for functions this executable lacks (see the header).",
              "#include \"%s\"" % HEADER, "#include <cstdio>", "#include <cstdlib>", ""]
    for n in missing:
        source += ["PS2_GUEST_CC void %s%s" % (n, sig), "{",
                   "    (void)rdram; (void)ctx; (void)runtime;",
                   "    std::fprintf(stderr, \"[compat] %s called: a VCS function this executable does not have\\n\");" % n,
                   "    std::fflush(stderr);",
                   "    std::abort();",
                   "}", ""]
    changed = write_if_changed(os.path.join(generated, HEADER), "\n".join(header) + "\n")
    changed |= write_if_changed(os.path.join(generated, SOURCE), "\n".join(source))
    print("[compat] %d functions named in src/ missing from this executable%s" % (len(missing), "" if changed else " (unchanged)"))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
